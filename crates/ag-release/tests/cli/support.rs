//! Temporary demo workspaces and the `ag-release` binary for command-line
//! tests.

use std::error::Error;
use std::os::unix::fs::{PermissionsExt, symlink};
use std::path::{Path, PathBuf};
use std::process::{Command, Output};
use std::{env, fs, io};

use flate2::Compression;
use flate2::write::GzEncoder;
use sha2::{Digest, Sha256};
use tempfile::{TempDir, tempdir};

/// The supported release target of the machine running the tests.
#[cfg(all(target_arch = "aarch64", target_os = "macos"))]
pub(crate) const HOST_TARGET: &str = "aarch64-apple-darwin";
#[cfg(all(target_arch = "x86_64", target_os = "macos"))]
pub(crate) const HOST_TARGET: &str = "x86_64-apple-darwin";
#[cfg(all(target_arch = "aarch64", target_os = "linux", target_env = "gnu"))]
pub(crate) const HOST_TARGET: &str = "aarch64-unknown-linux-gnu";
#[cfg(all(target_arch = "x86_64", target_os = "linux", target_env = "gnu"))]
pub(crate) const HOST_TARGET: &str = "x86_64-unknown-linux-gnu";

/// Every supported target, in triple order.
pub(crate) const TARGETS: [&str; 6] = [
    "aarch64-apple-darwin",
    "aarch64-unknown-linux-gnu",
    "aarch64-unknown-linux-musl",
    "x86_64-apple-darwin",
    "x86_64-unknown-linux-gnu",
    "x86_64-unknown-linux-musl",
];

/// Root manifest of a demo workspace released with `installers` for Linux
/// targets that mix glibc and musl: x86-64 has both, and 64-bit ARM has musl
/// only.
pub(crate) fn mixed_libc_manifest(installers: &str) -> String {
    format!(
        r#"[workspace]
members = ["demo-app"]
resolver = "2"

[workspace.metadata.release]
installers = [{installers}]
min-glibc = "2.17"

[workspace.metadata.release.targets]
aarch64-unknown-linux-musl = "demo-runner"
x86_64-unknown-linux-gnu = "demo-runner"
x86_64-unknown-linux-musl = "demo-runner"

[workspace.metadata.release.apps.demo-app]
"#
    )
}

/// The installers' error suffix naming every supported target.
pub(crate) const SUPPORTED: &str = "demo-app supports aarch64-apple-darwin, \
                                    aarch64-unknown-linux-gnu, x86_64-apple-darwin, \
                                    x86_64-unknown-linux-gnu";

/// Creates a demo workspace with the root `manifest` and a `README.md` in a
/// temporary directory. Each of `members`, a package directory named after
/// the package, holds a binary package without dependencies.
pub(crate) fn demo_workspace(manifest: &str, members: &[&str]) -> io::Result<TempDir> {
    let directory = tempdir()?;
    let root = directory.path();
    fs::write(root.join("Cargo.toml"), manifest)?;
    fs::write(root.join("Cargo.lock"), demo_lock(members))?;
    fs::write(root.join("README.md"), "# demo-app\n")?;
    for member in members {
        fs::create_dir_all(root.join(member).join("src"))?;
        fs::write(root.join(member).join("Cargo.toml"), demo_member(member))?;
        fs::write(root.join(member).join("src/main.rs"), "fn main() {}\n")?;
    }

    Ok(directory)
}

/// Creates the demo workspace with the root `manifest` and `members` as a
/// Git repository with one commit, as `assemble` needs for the source
/// archive.
pub(crate) fn committed_demo_workspace(manifest: &str, members: &[&str]) -> io::Result<TempDir> {
    let workspace = demo_workspace(manifest, members)?;
    for args in [
        &["init", "--quiet"][..],
        &["add", "--all"],
        &["commit", "--quiet", "--message", "Release demo"],
    ] {
        let status =
            isolate_git(Command::new("git").args(args).current_dir(workspace.path())).status()?;
        if !status.success() {
            return Err(io::Error::other(format!(
                "`git {}` failed: {status}",
                args.join(" ")
            )));
        }
    }

    Ok(workspace)
}

/// Returns the manifest of the demo member package `name`.
fn demo_member(name: &str) -> String {
    format!(
        r#"[package]
name = "{name}"
version = "0.1.0"
edition = "2024"
repository = "https://github.com/demo-org/demo-app"
"#
    )
}

/// Returns the lock file of a demo workspace of `members`, which have no
/// dependencies.
fn demo_lock(members: &[&str]) -> String {
    let mut members = members.to_vec();
    members.sort_unstable();
    let mut lock = String::from(
        "# This file is automatically @generated by Cargo.\n# It is not intended for manual \
         editing.\nversion = 4\n",
    );
    for name in members {
        lock.push_str("\n[[package]]\nname = \"");
        lock.push_str(name);
        lock.push_str("\"\nversion = \"0.1.0\"\n");
    }

    lock
}

/// Applies Git settings that keep host configuration out of a command.
pub(crate) fn isolate_git(command: &mut Command) -> &mut Command {
    command
        .env("GIT_CONFIG_GLOBAL", "/dev/null")
        .env("GIT_CONFIG_NOSYSTEM", "1")
        .env("GIT_AUTHOR_NAME", "Demo Author")
        .env("GIT_AUTHOR_EMAIL", "demo@example.com")
        .env("GIT_COMMITTER_NAME", "Demo Author")
        .env("GIT_COMMITTER_EMAIL", "demo@example.com")
}

/// Returns an `ag-release` command in `current_dir` without `CARGO`, as when
/// invoked outside Cargo, so it falls back to `cargo` on `PATH`.
pub(crate) fn ag_release(current_dir: &Path, args: &[&str]) -> Command {
    let mut command = Command::new(env!("CARGO_BIN_EXE_ag-release"));
    command
        .args(args)
        .current_dir(current_dir)
        .env_remove("CARGO");

    command
}

/// A release of the demo app for every target, assembled by `ag-release`.
pub(crate) struct Release {
    /// Artifacts directory holding the archives and the generated files.
    pub(crate) artifacts: TempDir,
    _workspace: TempDir,
}

impl Release {
    /// Writes an archive and checksum file for every target, whose `demo-app`
    /// binary is a shell script running `command(target)`, and assembles the
    /// release of a demo workspace with the root `manifest`.
    pub(crate) fn assemble(
        manifest: &str,
        command: impl Fn(&str) -> String,
    ) -> Result<Self, Box<dyn Error>> {
        let workspace = committed_demo_workspace(manifest, &["demo-app"])?;
        let artifacts = tempdir()?;
        for target in TARGETS {
            let archive = Self::archive(target, &command(target))?;
            let name = format!("demo-app-{target}.tar.gz");
            fs::write(
                artifacts.path().join(format!("{name}.sha256")),
                format!("{}  {name}\n", sha256(&archive)),
            )?;
            fs::write(artifacts.path().join(name), archive)?;
        }
        let directory = artifacts.path().to_str().ok_or("UTF-8 artifacts path")?;
        let assemble = ["assemble", "--tag", "v0.1.0", "--artifacts-dir", directory];
        let output = isolate_git(&mut ag_release(workspace.path(), &assemble)).output()?;
        if !output.status.success() {
            return Err(String::from_utf8_lossy(&output.stderr).into());
        }

        Ok(Self {
            artifacts,
            _workspace: workspace,
        })
    }

    /// Returns a `.tar.gz` holding `demo-app-<target>/demo-app`, a script
    /// that runs `command`.
    pub(crate) fn archive(target: &str, command: &str) -> io::Result<Vec<u8>> {
        let script = format!("#!/bin/sh\n{command}\n");
        let mut header = tar::Header::new_gnu();
        header.set_size(script.len() as u64);
        header.set_mode(0o755);
        let mut builder = tar::Builder::new(GzEncoder::new(Vec::new(), Compression::fast()));
        builder.append_data(
            &mut header,
            format!("demo-app-{target}/demo-app"),
            script.as_bytes(),
        )?;

        builder.into_inner()?.finish()
    }

    /// Returns the path of the release file `name`.
    pub(crate) fn artifact(&self, name: &str) -> PathBuf {
        self.artifacts.path().join(name)
    }
}

/// Writes an executable `sh` script running `command` to `path`.
pub(crate) fn write_executable(path: &Path, command: &str) -> io::Result<()> {
    fs::write(path, format!("#!/bin/sh\n{command}\n"))?;

    fs::set_permissions(path, fs::Permissions::from_mode(0o755))
}

/// Returns the lowercase hexadecimal SHA-256 of `contents`.
pub(crate) fn sha256(contents: &[u8]) -> String {
    hex::encode(Sha256::digest(contents))
}

/// Returns standard output of a successful run, or standard error.
pub(crate) fn result(output: &Output) -> Result<String, String> {
    let text = |bytes: &[u8]| String::from_utf8_lossy(bytes).into_owned();
    if output.status.success() {
        return Ok(text(&output.stdout));
    }

    Err(text(&output.stderr))
}

/// Links each of `tools` found on the host `PATH` into `directory`, so a
/// sandboxed `PATH` offers only those tools.
pub(crate) fn link_tools(directory: &Path, tools: &[&str]) -> io::Result<()> {
    let host_path = env::var_os("PATH").unwrap_or_default();
    for tool in tools {
        let found = env::split_paths(&host_path)
            .map(|candidate| candidate.join(tool))
            .find(|path| path.is_file());
        if let Some(path) = found {
            symlink(path, directory.join(tool))?;
        }
    }

    Ok(())
}
