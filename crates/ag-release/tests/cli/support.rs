//! Temporary demo workspaces and the `ag-release` binary for command-line
//! tests.

use std::path::Path;
use std::process::Command;
use std::{fs, io};

use tempfile::{TempDir, tempdir};

/// Manifest of the demo workspace's only member.
const DEMO_APP_MANIFEST: &str = r#"[package]
name = "demo-app"
version = "0.1.0"
edition = "2024"
repository = "https://github.com/demo-org/demo-app"
"#;

/// Lock file of the demo workspace, which has no dependencies.
const DEMO_LOCK: &str = r#"# This file is automatically @generated by Cargo.
# It is not intended for manual editing.
version = 4

[[package]]
name = "demo-app"
version = "0.1.0"
"#;

/// Creates a one-app demo workspace with the root `manifest` in a temporary
/// directory.
pub(crate) fn demo_workspace(manifest: &str) -> io::Result<TempDir> {
    let directory = tempdir()?;
    let root = directory.path();
    fs::write(root.join("Cargo.toml"), manifest)?;
    fs::write(root.join("Cargo.lock"), DEMO_LOCK)?;
    fs::write(root.join("README.md"), "# demo-app\n")?;
    fs::create_dir_all(root.join("demo-app/src"))?;
    fs::write(root.join("demo-app/Cargo.toml"), DEMO_APP_MANIFEST)?;
    fs::write(root.join("demo-app/src/main.rs"), "fn main() {}\n")?;

    Ok(directory)
}

/// Returns an `ag-release` command in `current_dir` without `CARGO`, as when
/// invoked outside Cargo, so it falls back to `cargo` on `PATH`.
pub(crate) fn ag_release(current_dir: &Path, args: &[&str]) -> Command {
    let mut command = Command::new(env!("CARGO_BIN_EXE_ag-release"));
    command
        .args(args)
        .current_dir(current_dir)
        .env_remove("CARGO");

    command
}
