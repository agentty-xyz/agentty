//! Release workflow generation unit tests: rendering against configured
//! workspaces, parsed back as YAML, and the command with mocked host
//! boundaries.

use std::ffi::OsString;
use std::path::PathBuf;

use serde_json::{Value, json};

use super::{ReleaseWorkflow, WORKFLOW_PATH};
use crate::cli::{Command, Host, WorkflowOptions};
use crate::workspace::Workspace;
use crate::workspace::test_support::{
    BrokenPipe, DEMO_ROOT, MemoryFiles, demo_metadata, lock, memory_file_system, memory_files,
    metadata_bytes, metadata_process,
};

/// A valid commit hash of only digits, which YAML would read as a number
/// unless quoted.
const REV: &str = "0123456789012345678901234567890123456789";

/// Default pin of `actions/checkout`.
const CHECKOUT: &str = "actions/checkout@3d3c42e5aac5ba805825da76410c181273ba90b1 # v7.0.1";

/// Jobs that run `ag-release`.
const TOOL_JOBS: [&str; 4] = ["plan", "smoke", "build", "assemble"];

/// Returns the demo metadata with `workflow` as its workflow table, or
/// without one for `None`.
fn metadata(workflow: Option<Value>) -> Value {
    let mut metadata = demo_metadata();
    if let Some(workflow) = workflow {
        metadata["metadata"]["release"]["workflow"] = workflow;
    }

    metadata
}

/// Returns the demo workspace of `metadata`, whose `ag-release` package is
/// `crates/ag-release`.
fn workspace(metadata: &Value) -> Workspace {
    let mut workspace = Workspace::from_metadata(&metadata_bytes(metadata)).expect("workspace");
    workspace.tool_directory = Some(PathBuf::from(DEMO_ROOT).join("crates/ag-release"));

    workspace
}

/// Renders `workspace`'s workflow and parses it as YAML.
fn render(workspace: &Workspace, existing: Option<&str>) -> (String, Value) {
    let text = ReleaseWorkflow::render(workspace, existing).expect("workflow");
    let yaml = serde_yaml_ng::from_str(&text).expect("valid YAML");

    (text, yaml)
}

/// Returns the job ids of `yaml` in file order.
fn job_ids(yaml: &Value) -> Vec<&str> {
    yaml["jobs"]
        .as_object()
        .expect("jobs")
        .keys()
        .map(String::as_str)
        .collect()
}

/// Returns the names of `job`'s steps.
fn step_names<'yaml>(yaml: &'yaml Value, job: &str) -> Vec<&'yaml str> {
    yaml["jobs"][job]["steps"]
        .as_array()
        .expect("steps")
        .iter()
        .filter_map(|step| step["name"].as_str())
        .collect()
}

/// Returns `job`'s step called `name`.
fn step<'yaml>(yaml: &'yaml Value, job: &str, name: &str) -> &'yaml Value {
    yaml["jobs"][job]["steps"]
        .as_array()
        .expect("steps")
        .iter()
        .find(|step| step["name"] == name)
        .expect("a step with that name")
}

/// Returns every step of every job.
fn steps(yaml: &Value) -> Vec<&Value> {
    yaml["jobs"]
        .as_object()
        .expect("jobs")
        .values()
        .filter_map(|job| job["steps"].as_array())
        .flatten()
        .collect()
}

/// Runs `workflow` with `options.check` against the demo workspace with a
/// Git tool source and `files`, and returns its result and output.
fn run_workflow(check: bool, files: &MemoryFiles) -> (Result<(), String>, String) {
    let process = metadata_process(&metadata(Some(git_tool())));
    let file_system = memory_file_system(files);
    let host = Host {
        cargo: OsString::from("cargo"),
        file_system: &file_system,
        process: &process,
        source_date_epoch: None,
    };
    let mut stdout = Vec::new();
    let result = host.run(&Command::Workflow(WorkflowOptions { check }), &mut stdout);

    (result, String::from_utf8(stdout).expect("UTF-8 output"))
}

/// Returns a workflow table that installs `ag-release` from Git.
fn git_tool() -> Value {
    json!({"tool": {"git": "https://example.com/demo-org/ag-release", "rev": REV}})
}

/// Returns the absolute path of the demo workspace's workflow.
fn workflow_path() -> PathBuf {
    PathBuf::from(DEMO_ROOT).join(WORKFLOW_PATH)
}

#[test]
fn render_builds_the_plain_pipeline_and_the_tool_from_the_workspace() {
    // Arrange
    let workspace = workspace(&metadata(None));

    // Act
    let (text, yaml) = render(&workspace, None);

    // Assert
    assert!(text.starts_with(
        "# Generated by `ag-release workflow`; do not edit. Change the release through\n# \
         `[workspace.metadata.release]`"
    ));
    assert_eq!(
        job_ids(&yaml),
        ["plan", "smoke", "build", "assemble", "host"]
    );
    assert_eq!(yaml["permissions"], json!({}));
    assert_eq!(
        yaml["on"]["push"]["tags"],
        json!(["v[0-9]+.[0-9]+.[0-9]+*"])
    );
    assert_eq!(
        yaml["jobs"]["host"]["needs"],
        json!(["plan", "build", "assemble"])
    );
    assert_eq!(
        yaml["jobs"]["host"]["if"],
        "${{ github.event_name == 'push' }}"
    );
    assert_eq!(
        step(&yaml, "plan", "Check that the release workflow is current")["run"],
        "ag-release workflow --check"
    );
    assert!(
        step(&yaml, "plan", "Detect release tooling changes")["run"]
            .as_str()
            .expect("script")
            .contains("paths=(\n  crates/ag-release\n  .github/workflows/release.yml\n)\n")
    );
    assert_eq!(
        yaml["jobs"]["smoke"]["strategy"]["matrix"]["runner"],
        json!(["macos-latest", "ubuntu-22.04"])
    );
    assert!(!step_names(&yaml, "smoke").contains(&"Setup Node"));
    assert!(!step_names(&yaml, "build").contains(&"Install musl tools"));
    assert_eq!(
        step(&yaml, "build", "Build archives")["env"],
        json!({"TARGET": "${{ matrix.target }}"})
    );
    for job in TOOL_JOBS {
        let names = step_names(&yaml, job);
        assert!(names.contains(&"Install the Rust toolchain"), "{job}");
        assert!(names.contains(&"Build `ag-release`"), "{job}");
    }
    for step in steps(&yaml) {
        let script = step["run"].as_str().unwrap_or_default();
        assert!(!script.contains("${{"), "{script}");
        if step["name"] == "Checkout" {
            assert_eq!(step["with"]["persist-credentials"], false);
            assert_eq!(step["uses"], CHECKOUT.split(' ').next().expect("ref"));
        }
    }
}

#[test]
fn render_installs_the_homebrew_formulas_in_smoke_when_configured() {
    // Arrange
    let without_homebrew = workspace(&metadata(None));
    let mut metadata = metadata(None);
    metadata["metadata"]["release"]["installers"] = json!(["homebrew"]);
    metadata["metadata"]["release"]["homebrew-tap"] = json!("demo-org/tap");
    let with_homebrew = workspace(&metadata);

    // Act
    let (_, yaml) = render(&with_homebrew, None);
    let (_, plain) = render(&without_homebrew, None);

    // Assert
    let step = step(&yaml, "smoke", "Install through Homebrew");
    assert_eq!(step["env"], json!({"TAG": "${{ needs.plan.outputs.tag }}"}));
    let script = step["run"].as_str().expect("script");
    assert!(
        script.contains("\"$brew\" install \"$tap/$app\" < /dev/null\n"),
        "{script}"
    );
    assert!(
        script.contains("sed \"s|\\\"$download_url/|\\\"file://$artifacts/|\""),
        "{script}"
    );
    assert!(!step_names(&plain, "smoke").contains(&"Install through Homebrew"));
}

